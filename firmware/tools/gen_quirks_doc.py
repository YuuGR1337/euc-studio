#!/usr/bin/env python3
"""Writes docs/quirks.md from config/quirks.def.

Usage:
    gen_quirks_doc.py           regenerate firmware/docs/quirks.md
    gen_quirks_doc.py --check   exit 1 if the file is missing or out of date (CI)

Python 3.11+ standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

FIRMWARE_DIR = Path(__file__).resolve().parent.parent
QUIRKS_DEF = FIRMWARE_DIR / "config" / "quirks.def"
QUIRKS_DOC = FIRMWARE_DIR / "docs" / "quirks.md"

C_STRING = r'"(?:[^"\\]|\\.)*"'
# A one-line group comment ("/* Commands and telemetry */") or one EUC_QUIRK_DEF entry, in file order.
TOKEN_RE = re.compile(
    r"^/\* (?P<title>[^*\n]+?) \*/$"
    r"|^EUC_QUIRK_DEF\(\s*(?P<id>\w+)\s*,\s*(?P<compat>[01])\s*,\s*(?P<clean>[01])\s*,\s*"
    rf"(?P<ref>{C_STRING})\s*,\s*(?P<summary>(?:{C_STRING}\s*)+)\)",
    re.MULTILINE,
)
ON_OFF = {"1": "on", "0": "off"}


def c_string_value(literals: str) -> str:
    """Joins adjacent C string literals and undoes the simple escapes used in quirks.def."""
    parts = re.findall(C_STRING, literals)
    return "".join(bytes(p[1:-1], "utf-8").decode("unicode_escape") for p in parts)


def render(def_text: str) -> str:
    out = [
        "# Firmware quirks",
        "",
        "Generated by `firmware/tools/gen_quirks_doc.py` from `firmware/config/quirks.def`.",
        "Do not edit by hand.",
        "",
        "Each quirk is a stock Begode Extreme behaviour that the **compat** profile reproduces, so our",
        "image can run in lock-step with the stock binary. The **clean** profile fixes it unless the",
        "Clean column says `on`. Code tests a quirk with `if (EUC_QUIRK(ID))`; target images resolve it",
        "at compile time, the SIL library at run time so the studio can switch one quirk at a time.",
        "The bit is the quirk's position in the SIL mask.",
    ]
    bit = 0
    for token in TOKEN_RE.finditer(def_text):
        if token.group("title"):
            out += ["", f"## {token.group('title')}", ""]
            out += ["| Bit | ID | Compat | Clean | Stock reference | Summary |", "|---|---|---|---|---|---|"]
            continue
        compat, clean = ON_OFF[token.group("compat")], ON_OFF[token.group("clean")]
        ref, summary = c_string_value(token.group("ref")), c_string_value(token.group("summary"))
        out.append(f"| {bit} | `{token.group('id')}` | {compat} | {clean} | {ref} | {summary} |")
        bit += 1
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/quirks.md is out of date")
    args = parser.parse_args()

    expected = render(QUIRKS_DEF.read_text(encoding="utf-8"))
    if args.check:
        current = QUIRKS_DOC.read_text(encoding="utf-8") if QUIRKS_DOC.exists() else ""
        if current != expected:
            doc = QUIRKS_DOC.relative_to(FIRMWARE_DIR)
            print(f"{doc} is out of date: run the quirks-doc target", file=sys.stderr)
            return 1
        return 0
    QUIRKS_DOC.parent.mkdir(parents=True, exist_ok=True)
    QUIRKS_DOC.write_text(expected, encoding="utf-8")
    print(f"wrote {QUIRKS_DOC.relative_to(FIRMWARE_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
