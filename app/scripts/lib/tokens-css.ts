// Renders src/design/tokens.ts into the Tailwind 4 @theme stylesheet. Pure and deterministic
// so `gen-tokens.ts --check` and the unit test can compare output byte for byte.

import { spring } from "motion";
import * as t from "../../src/design/tokens.ts";

const round = (v: number, digits = 4) => {
  const s = v.toFixed(digits).replace(/\.?0+$/, "");
  return s === "-0" ? "0" : s;
};

/**
 * Samples Motion's own spring (same duration/bounce as the JS token) into a CSS `linear()`
 * easing, so CSS hover/press transitions and Motion animations share one curve.
 */
export function springToLinear(duration: number, bounce: number, samples = 40): string {
  const ms = duration * 1000;
  const gen = spring({ keyframes: [0, 1], duration: ms, bounce });
  const points: string[] = [];
  for (let i = 0; i <= samples; i++) {
    const value = i === samples ? 1 : gen.next((ms * i) / samples).value;
    points.push(round(value));
  }
  return `linear(${points.join(", ")})`;
}

function block(selector: string, entries: [string, string | number][]): string {
  const body = entries.map(([k, v]) => `  ${k}: ${v};`).join("\n");
  return `${selector} {\n${body}\n}\n`;
}

export function renderTokensCss(): string {
  const accent = t.accents[t.DEFAULT_ACCENT];
  const theme: [string, string | number][] = [
    // Colors: replace Tailwind's palette entirely.
    ["--color-*", "initial"],
    ...Object.entries(t.surface).map(([k, v]): [string, string] => [`--color-${k}`, v]),
    ...Object.entries(t.text).map(([k, v]): [string, string] => [`--color-${k}`, v]),
    ["--color-accent", accent.accent],
    ["--color-accent-text", accent.text],
    ["--color-accent-tint", accent.tint],
    ["--color-accent-hover", accent.hover],
    ["--color-on-accent", t.ON_ACCENT],
    ...Object.entries(t.semantic).map(([k, v]): [string, string] => [`--color-${k}`, v]),
    ...Object.entries(t.series).map(([k, v]): [string, string] => [`--color-series-${k}`, v]),
    ...Object.entries(t.hairline).map(([k, v]): [string, string] => [`--color-${k}`, v]),
    ["--color-transparent", "transparent"],
    ["--color-current", "currentColor"],

    // Spacing: only 2/4/8/16/24/32/48. Class names are pixels (p-16 = 16px).
    ["--spacing", "initial"],
    ["--spacing-*", "initial"],
    ...t.spacing.map((v): [string, string] => [`--spacing-${v}`, `${v}px`]),

    // Radii.
    ["--radius-*", "initial"],
    ...Object.entries(t.radius).map(([k, v]): [string, string] => [`--radius-${k}`, v]),

    // Type.
    ["--font-*", "initial"],
    ["--font-ui", t.font.ui],
    ["--font-mono", t.font.mono],
    ["--text-*", "initial"],
    ...Object.entries(t.typeScale).flatMap(([size, [lh, ls]]): [string, string][] => [
      [`--text-${size}`, `${size}px`],
      [`--text-${size}--line-height`, `${lh}px`],
      [`--text-${size}--letter-spacing`, ls === "0" ? "0em" : ls],
    ]),

    // Motion: the four tokens plus the CSS hover curve.
    ["--ease-*", "initial"],
    ["--ease-snappy", springToLinear(t.motion.snappy.duration, t.motion.snappy.bounce)],
    ["--ease-smooth", springToLinear(t.motion.smooth.duration, t.motion.smooth.bounce)],
    ["--ease-bouncy", springToLinear(t.motion.bouncy.duration, t.motion.bouncy.bounce)],
    ["--ease-data", "linear"],
    ["--ease-hover", t.hover.ease],
    ["--default-transition-duration", `${t.hover.duration * 1000}ms`],
    ["--default-transition-timing-function", t.hover.ease],

    // Elevation is surface steps + hairlines. One soft shadow exists for floating overlays only.
    ["--shadow-*", "initial"],
    ["--shadow-overlay", "0 24px 64px -24px rgba(0, 0, 0, 0.7)"],
  ];

  const root: [string, string | number][] = [
    ["--dur-snappy", `${t.motion.snappy.duration * 1000}ms`],
    ["--dur-smooth", `${t.motion.smooth.duration * 1000}ms`],
    ["--dur-bouncy", `${t.motion.bouncy.duration * 1000}ms`],
    ["--dur-data", `${t.motion.data.duration * 1000}ms`],
    ["--dur-hover", `${t.hover.duration * 1000}ms`],
    ...Object.entries(t.size).map(([k, v]): [string, string] => [`--${k}`, `${v}px`]),
  ];

  const accentBlocks = Object.entries(t.accents)
    .filter(([name]) => name !== t.DEFAULT_ACCENT)
    .map(([name, a]) =>
      block(`[data-accent="${name}"]`, [
        ["--color-accent", a.accent],
        ["--color-accent-text", a.text],
        ["--color-accent-tint", a.tint],
        ["--color-accent-hover", a.hover],
      ]),
    );

  return [
    "/* GENERATED by scripts/gen-tokens.ts from src/design/tokens.ts. Do not edit by hand. */\n",
    block("@theme static", theme),
    block(":root", root),
    ...accentBlocks,
  ].join("\n");
}
